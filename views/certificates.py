import streamlit as st
import pandas as pd
from database import run_query

def render():
    current_mode = st.session_state.get('event_mode', 'Sports')
    st.title(f"🏅 {current_mode} Winner Certificates")
    st.markdown("Generate and print certificates for the winners of your events. You can use your browser's Print functionality (`Ctrl+P` or `Cmd+P`) to save these as PDFs or print them directly.")

    # Fetch programs that have scores
    query_progs = """
        SELECT DISTINCT p.id, p.name, p.type 
        FROM programs p
        JOIN scores s ON p.id = s.program_id
        WHERE p.event_mode = ?
    """
    try:
        df_prog = run_query(query_progs, (current_mode,))
    except Exception as e:
        df_prog = pd.DataFrame()

    if df_prog.empty:
        st.info("No events have scores logged yet. Add some scores to generate certificates!")
        return

    prog_display = [f"{row['name']} ({row['type']})" for _, row in df_prog.iterrows()]
    selected_prog_str = st.selectbox("Select an Event", prog_display)
    
    prog_idx = prog_display.index(selected_prog_str)
    prog_id = df_prog.iloc[prog_idx]['id']
    prog_name = df_prog.iloc[prog_idx]['name']

    # Fetch 1st and 2nd place winners for the selected program
    query_winners = f"""
        SELECT position, student_or_group_leader, group_name
        FROM scores
        WHERE program_id = {prog_id} AND position IN (1, 2)
        ORDER BY position ASC
    """
    df_winners = run_query(query_winners)

    if df_winners.empty:
        st.warning("No 1st or 2nd place winners found for this event.")
        return

    st.markdown("---")
    st.subheader("Generated Certificates")
    
    col1, col2 = st.columns([3, 1])
    with col2:
        print_btn = st.button("🖨️ Print / Download PDF", type="primary")
    
    # CSS for Certificate
    css = """
    <style>
    .certificate-container {
        border: 10px solid #D4AF37;
        padding: 40px;
        text-align: center;
        background-color: #ffffff;
        color: #333;
        font-family: 'Georgia', serif;
        margin-bottom: 30px;
        border-radius: 10px;
        box-shadow: 0 4px 8px rgba(0,0,0,0.1);
    }
    .cert-header {
        font-size: 36px;
        font-weight: bold;
        color: #D4AF37;
        margin-bottom: 20px;
        text-transform: uppercase;
        letter-spacing: 2px;
    }
    .cert-body {
        font-size: 24px;
        margin: 15px 0;
    }
    .cert-name {
        font-size: 40px;
        font-weight: bold;
        color: #2c3e50;
        text-decoration: underline;
        margin: 20px 0;
    }
    .cert-event {
        font-size: 30px;
        color: #e74c3c;
        font-weight: bold;
    }
    .cert-footer {
        font-size: 18px;
        margin-top: 40px;
        color: #7f8c8d;
    }
    @media print {
        /* Hide all Streamlit UI components when printing */
        header[data-testid="stHeader"], 
        [data-testid="stSidebar"], 
        [data-testid="stToolbar"], 
        footer { 
            display: none !important; 
        }
        /* Hide the Selectbox, Alerts, and Button during print */
        .stSelectbox, .stAlert, .stButton { 
            display: none !important; 
        }
        /* Ensure certificates take up full page width and start on new pages */
        .main .block-container { 
            max-width: 100% !important; 
            padding: 0 !important;
        }
        .certificate-container {
            page-break-after: always; /* Each certificate on a new page */
            box-shadow: none !important;
            border-width: 15px !important;
            margin: 0 !important;
        }
    }
    </style>
    """
    st.markdown(css, unsafe_allow_html=True)
    
    places = {1: "1st Place 🥇", 2: "2nd Place 🥈", 3: "3rd Place 🥉"}

    for _, row in df_winners.iterrows():
        pos = row['position']
        name = row['student_or_group_leader']
        group = row['group_name']
        place_text = places.get(pos, f"{pos}th Place")
        
        cert_html = f"""
        <div class="certificate-container">
            <div class="cert-header">Certificate of Achievement</div>
            <div class="cert-body">This is proudly presented to</div>
            <div class="cert-name">{name}</div>
            <div class="cert-body">of {group} for outstanding performance and securing</div>
            <div class="cert-body"><strong>{place_text}</strong></div>
            <div class="cert-body">in the event</div>
            <div class="cert-event">{prog_name}</div>
            <div class="cert-footer">Generated by School Sports Event Manager</div>
        </div>
        """
        st.markdown(cert_html, unsafe_allow_html=True)
        
    st.info("💡 Tip: You can also press `Ctrl+P` to open the print dialog directly.")
    
    if print_btn:
        import streamlit.components.v1 as components
        components.html(
            "<script>window.parent.print();</script>",
            height=0
        )
